// ignore_for_file: avoid_print
import 'dart:io';

void main() async {
  final projectRoot = Directory.current.path;
  final pigeonsDir = Directory('$projectRoot/pigeons');

  final parts = [
    'core_generation.dart',
    'story_list_generation.dart',
    'story_generation.dart',
    'callbacks_generation.dart',
    'games_generation.dart',
    'in_app_messages_generation.dart',
  ];

  final buffer = StringBuffer();
  buffer.writeln('// AUTOGENERATED PIGEON DEFINITION - DO NOT EDIT DIRECTLY.');
  buffer.writeln('// To make changes, edit the individual pigeon files in pigeons/:');
  for (final part in parts) {
    buffer.writeln('//   - $part');
  }
  buffer.writeln();
  buffer.writeln("import 'package:pigeon/pigeon.dart';");
  buffer.writeln();
  buffer.writeln('@ConfigurePigeon(PigeonOptions(');
  buffer.writeln("  dartOut: 'lib/src/generated/pigeon_generated.g.dart',");
  buffer.writeln('  dartOptions: DartOptions(),');
  buffer.writeln('  kotlinOut:');
  buffer.writeln("      'android/src/main/kotlin/com/inappstory/inappstory_plugin/PigeonGenerated.g.kt',");
  buffer.writeln('  kotlinOptions: KotlinOptions(),');
  buffer.writeln('  swiftOut:');
  buffer.writeln("      'ios/inappstory_plugin/Sources/inappstory_plugin/PigeonGenerated.g.swift',");
  buffer.writeln('  swiftOptions: SwiftOptions(),');
  buffer.writeln('))');
  buffer.writeln();

  for (final part in parts) {
    final file = File('${pigeonsDir.path}/$part');
    if (!file.existsSync()) {
      stderr.writeln('Warning: ${file.path} not found!');
      continue;
    }
    final content = file.readAsStringSync();
    final stripped = _stripPigeonBoilerplate(content, part);
    buffer.writeln('// ----------------------------------------------------');
    buffer.writeln('// Part: $part');
    buffer.writeln('// ----------------------------------------------------');
    buffer.writeln(stripped);
    buffer.writeln();
  }

  final targetFile = File('${pigeonsDir.path}/pigeon_generation.dart');
  targetFile.writeAsStringSync(buffer.toString());
  print('Successfully generated ${targetFile.path}');

  // List of all pigeon files to run
  final pigeonInputs = [
    'pigeons/pigeon_generation.dart',
    'pigeons/core_generation_private.dart',
    'pigeons/appearance_manager.dart',
    'pigeons/story_manager_generation.dart',
    'pigeons/banner_place_generation.dart',
    'pigeons/checkout_generation.dart',
  ];

  for (final input in pigeonInputs) {
    print('Running pigeon on $input...');
    final result = await Process.run('dart', ['run', 'pigeon', '--input', input]);
    if (result.exitCode != 0) {
      stderr.writeln('Error running pigeon on $input:');
      stderr.writeln(result.stderr);
      stderr.writeln(result.stdout);
      exit(result.exitCode);
    }
  }

  print('All pigeons successfully generated! 🕊️');
}

String _stripPigeonBoilerplate(String content, String filename) {
  final lines = content.split('\n');
  final result = <String>[];
  bool inConfigurePigeon = false;
  int parenDepth = 0;

  for (final line in lines) {
    final trimmed = line.trim();

    // Skip import lines
    if (trimmed.startsWith('import ') && trimmed.endsWith(';')) {
      continue;
    }

    // Skip @ConfigurePigeon block
    if (trimmed.startsWith('@ConfigurePigeon(')) {
      inConfigurePigeon = true;
      parenDepth = 0;
    }

    if (inConfigurePigeon) {
      for (var i = 0; i < line.length; i++) {
        if (line[i] == '(') parenDepth++;
        if (line[i] == ')') parenDepth--;
      }
      if (parenDepth <= 0 && trimmed.contains(')')) {
        inConfigurePigeon = false;
      }
      continue;
    }

    if (trimmed == '// ConfigurePigeon' || trimmed.startsWith('// run in the root folder')) {
      continue;
    }

    result.add(line);
  }

  return result.join('\n').trim();
}
